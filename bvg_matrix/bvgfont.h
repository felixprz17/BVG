inline int layoutSize(int size, bool bold) {
  if (size < 0) size = 0;
  if (size > 2) size = 2;
  return (bold && size == 0) ? 1 : size;
}
inline const Font& pick(int size, bool bold) {
  static const Font* const plain[3] = {&FONT_PLAIN_S, &FONT_PLAIN_M, &FONT_PLAIN_L};
  static const Font* const fat[3] = {&FONT_BOLD_M, &FONT_BOLD_M, &FONT_BOLD_L};
  if (size < 0) size = 0;
  if (size > 2) size = 2;
  return bold ? *fat[size] : *plain[size];
}

inline int glyphIndex(uint32_t cp) {
  if (cp >= 32 && cp <= 126) return (int)cp - 32;
  if (cp >= 0xA0 && cp <= 0xFF) return 95 + (int)cp - 0xA0;
  return -1;
}

inline const Glyph& glyphFor(const Font& f, uint32_t cp) {
  int i = glyphIndex(cp);
  if (i < 0) i = '?' - 32;
  return f.g[i];
}

// naechstes Zeichen aus UTF-8 lesen (ungueltig/ausserhalb Latin-1 -> '?')
inline uint32_t nextCp(const std::string& s, size_t& i) {
  unsigned char c = (unsigned char)s[i++];
  if (c < 0x80) return c;
  int extra = (c >= 0xF0) ? 3 : (c >= 0xE0) ? 2 : (c >= 0xC0) ? 1 : 0;
  uint32_t cp = (extra == 1) ? (c & 0x1F) : (extra == 2) ? (c & 0x0F) : (extra == 3) ? (c & 0x07) : '?';
  for (int k = 0; k < extra && i < s.size() && ((unsigned char)s[i] & 0xC0) == 0x80; k++)
    cp = (cp << 6) | ((unsigned char)s[i++] & 0x3F);
  return cp;
}

