inline Extent inkExtent(const Font& f, const std::string& s) {
  int pen = 0, lo = 1 << 20, hi = -(1 << 20);
  for (size_t i = 0; i < s.size();) {
    const Glyph& g = glyphFor(f, nextCp(s, i));
    if (g.w) {
      if (pen + g.xo < lo) lo = pen + g.xo;
      if (pen + g.xo + g.w > hi) hi = pen + g.xo + g.w;
    }
    pen += g.adv;
  }
  Extent e;
  if (hi > lo) {
    e.left = lo;
    e.width = hi - lo;
  }
  return e;
}

// px(x, y): Pixel setzen. xInk = Spalte der ersten Tintenspalte. base = Zeile direkt unter der Grundlinie.
template <class Px>
inline void draw(const Font& f, const std::string& s, int xInk, int base, Px px) {
  int pen = xInk - inkExtent(f, s).left;
  for (size_t i = 0; i < s.size();) {
    const Glyph& g = glyphFor(f, nextCp(s, i));
    for (int r = 0; r < g.h; r++) {
      uint16_t row = f.bits[g.off + r];
      for (int c = 0; c < g.w; c++)
        if ((row >> (g.w - 1 - c)) & 1) px(pen + g.xo + c, base - g.top + r);
    }
    pen += g.adv;
  }
}

// auf maxW Pixel kuerzen; gekuerzt wird mit "." markiert
inline std::string fit(const Font& f, std::string s, int maxW) {
  if (inkExtent(f, s).width <= maxW) return s;
  while (!s.empty()) {
    size_t k = s.size() - 1;
    while (k > 0 && ((unsigned char)s[k] & 0xC0) == 0x80) k--;
    s.erase(k);
    while (!s.empty() && s.back() == ' ') s.pop_back();
    if (inkExtent(f, s + ".").width <= maxW) return s + ".";
  }
  return "";
}

